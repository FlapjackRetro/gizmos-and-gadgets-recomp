#!/usr/bin/env python3
"""embed_image.py - emit the flattened load image as C (src/gen/image_data.c).

The lifted functions are code; the image still holds the game's initial data,
its switch tables and its constants, and the runtime copies it into guest
memory at boot exactly as the DOS loader would, relocations included.

Usage: python tools/embed_image.py [work/ssg_flat.exe]
"""
import os
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    exe = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "work", "ssg_flat.exe")
    d = open(exe, "rb").read()
    cblp, cp, crlc, cpar = struct.unpack_from("<4H", d, 2)
    ss, sp, _csum, ip, cs, lfarlc = struct.unpack_from("<6H", d, 0x0E)
    hdr = cpar * 16
    img = d[hdr:]
    relocs = [struct.unpack_from("<HH", d, lfarlc + 4 * i) for i in range(crlc)]
    out = os.path.join(ROOT, "src", "gen", "image_data.c")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("/* generated by tools/embed_image.py from the player's own ssg.exe -- do not commit */\n")
        f.write("#include <stdint.h>\n#include <stddef.h>\n")
        f.write(f"const uint16_t g_img_ss = 0x{ss:04X}, g_img_sp = 0x{sp:04X}, "
                f"g_img_cs = 0x{cs:04X}, g_img_ip = 0x{ip:04X};\n")
        f.write(f"const size_t g_img_size = {len(img)};\n")
        f.write(f"const size_t g_img_nrelocs = {len(relocs)};\n")
        f.write("const uint16_t g_img_relocs[][2] = {\n")
        for i in range(0, len(relocs), 8):
            f.write("  " + ", ".join(f"{{0x{s:04X},0x{o:04X}}}" for o, s in relocs[i:i + 8]) + ",\n")
        f.write("};\n")
        f.write("const uint8_t g_img[] = {\n")
        for i in range(0, len(img), 32):
            f.write("  " + ",".join(str(b) for b in img[i:i + 32]) + ",\n")
        f.write("};\n")
    print(f"embedded {len(img)} bytes, {len(relocs)} relocations, entry {cs:04X}:{ip:04X}, "
          f"stack {ss:04X}:{sp:04X} -> {out}")


if __name__ == "__main__":
    main()
